-- Schema capture for off-site backups.
--
-- A backup of rows alone cannot be restored into a project that has lost its
-- tables, and 14 of the tables in this project (accounts, transactions,
-- business_profiles, subscriptions and the skt_* tables among them) are not
-- created by any migration in this repository. So each nightly backup also asks
-- the database to describe its own public schema, and stores that description
-- (inside the encrypted file) next to the data.
--
-- public.backup_schema_ddl() returns one SQL script that recreates:
--   extensions, sequences, tables (columns, defaults, identity, generated
--   columns, primary/unique/check constraints), indexes, foreign keys, row
--   level security flags, policies, triggers, functions, and the privileges
--   granted to the API roles.
--
-- It is built from Postgres's own catalog functions (pg_get_functiondef,
-- pg_get_indexdef, pg_get_constraintdef, ...) rather than hand-rolled, so what
-- it prints is what Postgres itself would print. The script is idempotent: it
-- can be run on a database that already has some or all of these objects.
--
-- NOT captured, on purpose or because they need superuser:
--   * data (that is the rest of the backup)
--   * sequence positions (re-set after a restore; see docs/OFFSITE_BACKUP.md)
--   * event triggers, roles and their passwords, views (reported in a comment)
--
-- Read-only: it only reads catalogs. Execution is limited to service_role, so
-- the schema (policy expressions, function bodies) is not handed to the public
-- API.

create or replace function public.backup_schema_ddl()
returns text
language plpgsql
stable
set search_path = pg_catalog, pg_temp
as $fn$
declare
  out  text := '';
  r    record;
  g    record;
  cols text;
  cons text;
  nl   constant text := E'\n';
  api_roles constant text[] := array['anon', 'authenticated', 'service_role'];
begin
  out := out || format('-- RupeeLedger public schema, generated %s by public.backup_schema_ddl()%s',
                       to_char(now() at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'), nl) || nl;

  -- extensions -----------------------------------------------------------------
  for r in
    select e.extname, n.nspname
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
    where e.extname <> 'plpgsql'
    order by e.extname
  loop
    out := out || format('create extension if not exists %I with schema %I;%s', r.extname, r.nspname, nl);
  end loop;
  out := out || nl;

  -- sequences (identity sequences are created with their table) ----------------
  for r in
    select c.relname, s.seqtypid::regtype::text as typ, s.seqstart, s.seqincrement,
           s.seqmin, s.seqmax, s.seqcache, s.seqcycle
    from pg_class c join pg_sequence s on s.seqrelid = c.oid
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'S'
      and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
    order by c.relname
  loop
    out := out || format('create sequence if not exists public.%I as %s increment by %s minvalue %s maxvalue %s start with %s cache %s %s;%s',
                         r.relname, r.typ, r.seqincrement, r.seqmin, r.seqmax, r.seqstart, r.seqcache,
                         case when r.seqcycle then 'cycle' else 'no cycle' end, nl);
  end loop;
  out := out || nl;

  -- tables ------------------------------------------------------------------------
  for r in
    select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.relacl, c.relowner
    from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p')
      and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
    order by c.relname
  loop
    select string_agg(
             '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
             || case a.attidentity
                  when 'a' then ' generated always as identity'
                  when 'd' then ' generated by default as identity'
                  else '' end
             || case
                  when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                  when d.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(d.adbin, d.adrelid)
                  else '' end
             || case when a.attnotnull then ' not null' else '' end,
             E',\n' order by a.attnum)
      into cols
    from pg_attribute a
    left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped;

    -- Foreign keys are added after every table exists; the rest live in the table.
    select string_agg('  constraint ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid),
                      E',\n' order by con.contype, con.conname)
      into cons
    from pg_constraint con
    where con.conrelid = r.oid and con.contype in ('p', 'u', 'c', 'x');

    out := out || format('create table if not exists public.%I (%s%s%s);%s',
                         r.relname, nl, cols || coalesce(E',\n' || cons, ''), nl, nl);

    if r.relrowsecurity then
      out := out || format('alter table public.%I enable row level security;%s', r.relname, nl);
    end if;
    if r.relforcerowsecurity then
      out := out || format('alter table public.%I force row level security;%s', r.relname, nl);
    end if;

    -- Privileges for the API roles, stated exactly (a revoke is as meaningful as a grant).
    out := out || format('revoke all on table public.%I from public, anon, authenticated, service_role;%s', r.relname, nl);
    for g in
      select case when a.grantee = 0 then 'public' else (select rolname from pg_roles where oid = a.grantee) end as grantee,
             string_agg(a.privilege_type, ', ' order by a.privilege_type) as privs
      from aclexplode(coalesce(r.relacl, acldefault('r', r.relowner))) a
      group by a.grantee
      having (case when a.grantee = 0 then 'public' else (select rolname from pg_roles where oid = a.grantee) end)
             = any (array['public'] || api_roles)
      order by 1
    loop
      out := out || format('grant %s on table public.%I to %s;%s', g.privs, r.relname, g.grantee, nl);
    end loop;
    out := out || nl;
  end loop;

  -- sequence ownership (so dropping a column drops its sequence, as before) --------
  for r in
    select s.relname as seq, t.relname as tbl, a.attname as col
    from pg_depend d
    join pg_class s on s.oid = d.objid and s.relkind = 'S'
    join pg_class t on t.oid = d.refobjid
    join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
    where d.deptype = 'a' and s.relnamespace = 'public'::regnamespace and t.relnamespace = 'public'::regnamespace
    order by s.relname
  loop
    out := out || format('alter sequence public.%I owned by public.%I.%I;%s', r.seq, r.tbl, r.col, nl);
  end loop;
  out := out || nl;

  -- indexes not already created by a constraint -----------------------------------
  for r in
    select pg_get_indexdef(i.indexrelid) as def
    from pg_index i
    join pg_class c on c.oid = i.indrelid
    join pg_class ic on ic.oid = i.indexrelid
    where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p')
      and not i.indisprimary
      and not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
    order by c.relname, ic.relname
  loop
    out := out || regexp_replace(r.def, '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || ';' || nl;
  end loop;
  out := out || nl;

  -- foreign keys ----------------------------------------------------------------------
  for r in
    select c.relname, con.conname, pg_get_constraintdef(con.oid) as def
    from pg_constraint con join pg_class c on c.oid = con.conrelid
    where con.contype = 'f' and c.relnamespace = 'public'::regnamespace
    order by c.relname, con.conname
  loop
    out := out || format('do $fk$ begin alter table public.%I add constraint %I %s; exception when duplicate_object then null; end $fk$;%s',
                         r.relname, r.conname, r.def, nl);
  end loop;
  out := out || nl;

  -- row level security policies ----------------------------------------------------------
  for r in
    select * from pg_policies where schemaname = 'public' order by tablename, policyname
  loop
    out := out || format('drop policy if exists %I on public.%I;%s', r.policyname, r.tablename, nl)
      || format('create policy %I on public.%I as %s for %s to %s%s%s;%s',
                r.policyname, r.tablename, lower(r.permissive), lower(r.cmd),
                (select string_agg(case when x = 'public' then 'public' else quote_ident(x) end, ', ') from unnest(r.roles) x),
                case when r.qual is not null then ' using (' || r.qual || ')' else '' end,
                case when r.with_check is not null then ' with check (' || r.with_check || ')' else '' end,
                nl);
  end loop;
  out := out || nl;

  -- functions and procedures (extension-owned ones are skipped) ------------------------------
  for r in
    select p.oid, p.proacl, p.proowner, pg_get_functiondef(p.oid) as def
    from pg_proc p
    where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    order by p.proname, p.oid::regprocedure::text
  loop
    out := out || rtrim(r.def, E' \n') || ';' || nl
      || format('revoke all on function %s from public, anon, authenticated, service_role;%s', r.oid::regprocedure, nl);
    for g in
      select case when a.grantee = 0 then 'public' else (select rolname from pg_roles where oid = a.grantee) end as grantee
      from aclexplode(coalesce(r.proacl, acldefault('f', r.proowner))) a
      where a.privilege_type = 'EXECUTE'
        and (case when a.grantee = 0 then 'public' else (select rolname from pg_roles where oid = a.grantee) end)
            = any (array['public'] || api_roles)
      order by 1
    loop
      out := out || format('grant execute on function %s to %s;%s', r.oid::regprocedure, g.grantee, nl);
    end loop;
    out := out || nl;
  end loop;

  -- triggers ----------------------------------------------------------------------------------
  for r in
    select pg_get_triggerdef(t.oid) as def, c.relname, t.tgname
    from pg_trigger t join pg_class c on c.oid = t.tgrelid
    where not t.tgisinternal and c.relnamespace = 'public'::regnamespace
    order by c.relname, t.tgname
  loop
    out := out || format('drop trigger if exists %I on public.%I;%s', r.tgname, r.relname, nl) || r.def || ';' || nl;
  end loop;

  -- things this script does not recreate -----------------------------------------------------
  for r in
    select c.relname from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind in ('v', 'm') order by c.relname
  loop
    out := out || format('-- NOT CAPTURED: view/materialized view public.%I must be recreated by hand%s', r.relname, nl);
  end loop;

  return out;
end;
$fn$;

-- Only the server (service_role) may call it. Without this revoke, Supabase's
-- default privileges would let anon and authenticated call it too.
revoke all on function public.backup_schema_ddl() from public, anon, authenticated;
grant execute on function public.backup_schema_ddl() to service_role;
